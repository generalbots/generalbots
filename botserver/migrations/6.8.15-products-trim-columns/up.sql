-- Move rarely-queried product metadata into the `attributes` JSONB column and
-- drop the dedicated columns so the `products` table fits in diesel's
-- 32-column-tables limit (lowers compile memory, see issue #1926).
UPDATE products
SET attributes = COALESCE(attributes, '{}'::jsonb) || jsonb_strip_nulls(jsonb_build_object(
    'weight', weight,
    'dimensions', dimensions,
    'barcode', barcode,
    'tax_code', tax_code,
    'tax_class', tax_class,
    'global_trade_number', global_trade_number,
    'net_weight', net_weight,
    'gross_weight', gross_weight,
    'width', width,
    'height', height,
    'length', length,
    'brand', brand,
    'model', model,
    'color', color,
    'size', size,
    'material', material,
    'gender', gender,
    'expiration_date', expiration_date,
    'min_stock', min_stock,
    'max_stock', max_stock,
    'reorder_point', reorder_point,
    'shipping_cost', shipping_cost,
    'external_id', external_id,
    'external_metadata', external_metadata,
    'slug', slug,
    'meta_description', meta_description,
    'tags', tags
));

ALTER TABLE products
    DROP COLUMN IF EXISTS weight,
    DROP COLUMN IF EXISTS dimensions,
    DROP COLUMN IF EXISTS barcode,
    DROP COLUMN IF EXISTS tax_code,
    DROP COLUMN IF EXISTS tax_class,
    DROP COLUMN IF EXISTS global_trade_number,
    DROP COLUMN IF EXISTS net_weight,
    DROP COLUMN IF EXISTS gross_weight,
    DROP COLUMN IF EXISTS width,
    DROP COLUMN IF EXISTS height,
    DROP COLUMN IF EXISTS length,
    DROP COLUMN IF EXISTS brand,
    DROP COLUMN IF EXISTS model,
    DROP COLUMN IF EXISTS color,
    DROP COLUMN IF EXISTS size,
    DROP COLUMN IF EXISTS material,
    DROP COLUMN IF EXISTS gender,
    DROP COLUMN IF EXISTS expiration_date,
    DROP COLUMN IF EXISTS min_stock,
    DROP COLUMN IF EXISTS max_stock,
    DROP COLUMN IF EXISTS reorder_point,
    DROP COLUMN IF EXISTS shipping_cost,
    DROP COLUMN IF EXISTS external_id,
    DROP COLUMN IF EXISTS external_metadata,
    DROP COLUMN IF EXISTS slug,
    DROP COLUMN IF EXISTS meta_description,
    DROP COLUMN IF EXISTS tags;
