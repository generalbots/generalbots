//! #2613 — pure deploy-key policy for the privileged deploy gateway.
//!
//! The old gateway accepted a comma-separated static `DEPLOY_KEYS` shared by
//! every deployment. A per-deployment secret must instead be a high-entropy
//! token of the kind produced by `generate_random_string(48)`, delivered from
//! Vault (`gbo/alm` -> `deploy_key`) or the narrowly-scoped `GB_DEPLOY_KEY`
//! environment variable. The helpers here are deliberately free of I/O so the
//! policy can be unit-tested without a server, Vault or environment.

/// Configured secret environment variable (single key, never a comma list).
pub(super) const DEPLOY_KEY_ENV: &str = "GB_DEPLOY_KEY";
/// Vault field inside `secret/gbo/alm` holding the per-deployment secret.
pub(super) const DEPLOY_KEY_VAULT_FIELD: &str = "deploy_key";

const MIN_KEY_LEN: usize = 32;
const MAX_KEY_LEN: usize = 256;

/// Long, low-entropy values that would otherwise satisfy the length rule.
/// A random 48-character token cannot contain one of these by chance.
const FORBIDDEN_KEYS: &[&str] = &[
    "00000000000000000000000000000000",
    "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa",
    "abcdefghijklmnopqrstuvwxyz123456",
    "12345678901234567890123456789012",
    "changemechangemechangemechangeme",
    "deploykeydeploykeydeploykeydeploy",
];

/// A deploy key must be a long alphanumeric token mixing character classes,
/// as generated by `generate_random_string`. Short/placeholder values, the
/// legacy comma-separated form, and non-alphanumeric input are all refused so
/// an operator cannot accidentally reintroduce a static shared key (#2613).
pub(super) fn is_strong_deploy_key(key: &str) -> bool {
    let key = key.trim();
    if key.len() < MIN_KEY_LEN || key.len() > MAX_KEY_LEN {
        return false;
    }
    if !key.bytes().all(|byte| byte.is_ascii_alphanumeric()) {
        return false;
    }
    // The legacy mechanism was a comma-separated list of static keys. Never
    // let a leftover `DEPLOY_KEYS` value become the new secret.
    if key.contains(',') {
        return false;
    }
    let lower = key.to_ascii_lowercase();
    if FORBIDDEN_KEYS.contains(&lower.as_str()) {
        return false;
    }
    let has_lower = key.bytes().any(|byte| byte.is_ascii_lowercase());
    let has_upper = key.bytes().any(|byte| byte.is_ascii_uppercase());
    let has_digit = key.bytes().any(|byte| byte.is_ascii_digit());
    has_lower && has_upper && has_digit
}

/// Pick the first strong key from the configured sources, Vault first.
/// `None` means no source supplied a usable secret and the caller must fail
/// closed (e.g. by generating an ephemeral key nobody outside the process has).
pub(super) fn resolve_deploy_key(vault: Option<&str>, env: Option<&str>) -> Option<String> {
    [vault, env]
        .into_iter()
        .flatten()
        .map(str::trim)
        .find(|key| is_strong_deploy_key(key))
        .map(str::to_owned)
}

#[cfg(test)]
mod tests {
    use super::{is_strong_deploy_key, resolve_deploy_key};

    const STRONG: &str = "aB3dE7gH1jK4mN8pQ2rS6tV9xZ5cF0wL";

    #[test]
    fn accepts_generated_style_key() {
        assert_eq!(STRONG.len(), 32);
        assert!(is_strong_deploy_key(STRONG));
        assert!(is_strong_deploy_key("  aB3dE7gH1jK4mN8pQ2rS6tV9xZ5cF0wL  "));
    }

    #[test]
    fn rejects_short_weak_and_placeholder_keys() {
        assert!(!is_strong_deploy_key(""));
        assert!(!is_strong_deploy_key("short"));
        assert!(!is_strong_deploy_key("changeme"));
        assert!(!is_strong_deploy_key("aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"));
        assert!(!is_strong_deploy_key("12345678901234567890123456789012"));
        assert!(!is_strong_deploy_key("abcdefghijklmnopqrstuvwxyz123456"));
    }

    #[test]
    fn rejects_legacy_static_list_and_unsafe_characters() {
        assert!(!is_strong_deploy_key(&format!("{STRONG},{STRONG}")));
        assert!(!is_strong_deploy_key("aB3dE7gH1jK4mN8pQ2rS6tV9xZ5cF0wL!"));
        assert!(!is_strong_deploy_key("aB3dE7gH1jK4m N8pQ2rS6tV9xZ5cF0wL"));
        assert!(!is_strong_deploy_key("aB3dE7gH1jK4m\nN8pQ2rS6tV9xZ5cF0wL"));
    }

    #[test]
    fn resolve_prefers_vault_and_ignores_weak_sources() {
        let other = "zY9xW8vU7tS6rQ5pO4nM3lK2jH1gF0dC";
        assert_eq!(resolve_deploy_key(Some(STRONG), Some(other)).as_deref(), Some(STRONG));
        assert_eq!(resolve_deploy_key(None, Some(STRONG)).as_deref(), Some(STRONG));
        assert_eq!(resolve_deploy_key(Some("weak"), Some(STRONG)).as_deref(), Some(STRONG));
        assert_eq!(resolve_deploy_key(Some("weak"), None), None);
        assert_eq!(resolve_deploy_key(None, None), None);
    }
}
