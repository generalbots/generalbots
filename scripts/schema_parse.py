#!/usr/bin/env python3
"""Parsing half of the database reference generator (issue #2078).

Reads `botschema/src/**` (`table!`, `joinable!`) and
`botserver/migrations/*/up.sql` (primary keys, nullability, defaults, indexes,
`REFERENCES`) into one inventory dict. Imported by
`scripts/gen_schema_reference.py`; standard library only.
"""

from __future__ import annotations

import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SCHEMA_DIR = REPO / "botschema" / "src"
MIGRATIONS_DIR = REPO / "botserver" / "migrations"
BOOK_REF = REPO / "botbook" / "src" / "12-ecosystem-reference"
OUT_DIR = BOOK_REF / "schema"
GEN_NOTE = "<!-- generated by scripts/gen_schema_reference.py — do not edit by hand -->"

RUST_TO_SQL = {
    "Uuid": "uuid", "Text": "text", "Varchar": "varchar", "Bool": "boolean",
    "Timestamptz": "timestamptz", "Timestamp": "timestamp", "Date": "date",
    "Time": "time", "Int2": "smallint", "Int4": "integer", "Int8": "bigint",
    "Float4": "real", "Float8": "double precision", "Numeric": "numeric",
    "Decimal": "numeric", "Jsonb": "jsonb", "Json": "json", "Bytea": "bytea",
    "Inet": "inet", "Citext": "citext", "Money": "money", "Float": "double precision",
    "Double": "double precision", "BigInt": "bigint", "SmallInt": "smallint",
}


def strip_sql_comments(sql: str) -> str:
    """Drop `--` and `/* */` comments so indented or commented DDL is not read as SQL."""
    out, i, quote = [], 0, None
    while i < len(sql):
        ch = sql[i]
        if quote:
            out.append(ch)
            if ch == quote:
                quote = None
            i += 1
        elif ch in "'\"":
            quote = ch
            out.append(ch)
            i += 1
        elif sql.startswith("--", i):
            j = sql.find("\n", i)
            i = len(sql) if j < 0 else j
        elif sql.startswith("/*", i):
            j = sql.find("*/", i + 2)
            i = len(sql) if j < 0 else j + 2
        else:
            out.append(ch)
            i += 1
    return "".join(out)


def sql_type_for(rust_type: str) -> str:
    """`Nullable<Array<Varchar>>` -> `varchar[]`; unknown types stay verbatim."""
    text = "".join(rust_type.split())
    while text.startswith("Nullable<") and text.endswith(">"):
        text = text[len("Nullable<"):-1]
    if text.startswith("Array<") and text.endswith(">"):
        return sql_type_for(text[len("Array<"):-1]) + "[]"
    return RUST_TO_SQL.get(text, text.lower())


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


def strip_rust_comments(text: str) -> str:
    """Drop // and /* */ comments while leaving string literals intact."""
    out, i, n = [], 0, len(text)
    while i < n:
        ch = text[i]
        if ch == '"':
            j = i + 1
            while j < n:
                if text[j] == "\\":
                    j += 2
                    continue
                if text[j] == '"':
                    break
                j += 1
            out.append(text[i:j + 1])
            i = j + 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            i = n if j < 0 else j + 2
        else:
            out.append(ch)
            i += 1
    return "".join(out)


def match_block(text: str, start: int, open_ch: str = "{", close_ch: str = "}") -> int:
    depth, i = 0, start
    while i < len(text):
        if text[i] == open_ch:
            depth += 1
        elif text[i] == close_ch:
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return len(text) - 1


def rust_files() -> list[Path]:
    return sorted(SCHEMA_DIR.rglob("*.rs"))


def module_features() -> dict[str, str]:
    """module name -> feature gate declared in lib.rs ('' for core/always-on)."""
    lib = read(SCHEMA_DIR / "lib.rs")
    gates: dict[str, str] = {}
    pending: str | None = None
    for line in lib.splitlines():
        s = line.strip()
        if s.startswith("#[cfg("):
            pending = s
        elif s.startswith("pub mod "):
            mod = s[len("pub mod "):].rstrip(";").strip()
            gates[mod] = pending or ""
            pending = None
        elif s and not s.startswith("pub use") and not s.startswith("//"):
            pending = None
    return gates


def feature_of(path: Path, gates: dict[str, str]) -> str:
    rel = path.relative_to(SCHEMA_DIR)
    mod = rel.parts[0].removesuffix(".rs")
    return gates.get(mod, "")


def parse_tables(path: Path) -> list[dict]:
    raw = read(path)
    text = strip_rust_comments(raw)
    tables: list[dict] = []
    for m in re.finditer(r"\btable!\s*\{", text):
        start = text.index("{", m.start())
        end = match_block(text, start)
        body = text[start + 1:end]
        header = re.match(r"\s*([A-Za-z_][A-Za-z0-9_]*)\s*(?:\(([^)]*)\))?\s*\{", body)
        if not header:
            continue
        name, pk_cols = header.group(1), header.group(2) or ""
        inner_start = header.end() - 1
        inner = body[inner_start:match_block(body, inner_start) + 1]
        cols = []
        for col in re.finditer(r"([A-Za-z_][A-Za-z0-9_]*)\s*->\s*([A-Za-z_][A-Za-z0-9_:<>, ]*?)\s*,\s*(?=[A-Za-z_#]|\})", inner):
            cols.append({"name": col.group(1), "rust_type": " ".join(col.group(2).split())})
        pks = [c.strip() for c in pk_cols.split(",") if c.strip()]
        tables.append({"name": name, "columns": cols, "pk": pks, "source": str(path.relative_to(REPO))})
    return tables


def parse_joinables(path: Path) -> list[dict]:
    text = strip_rust_comments(read(path))
    edges = []
    for m in re.finditer(r"joinable!\s*\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*->\s*([A-Za-z_][A-Za-z0-9_]*)\s*\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)\s*\)", text):
        edges.append({"from": m.group(1), "to": m.group(2), "column": m.group(3)})
    return edges


def split_top_level(body: str) -> list[str]:
    parts, depth, cur, quote = [], 0, [], None
    for ch in body:
        if quote:
            cur.append(ch)
            if ch == quote:
                quote = None
            continue
        if ch in "'\"":
            quote = ch
            cur.append(ch)
        elif ch == "(":
            depth += 1
            cur.append(ch)
        elif ch == ")":
            depth -= 1
            cur.append(ch)
        elif ch == "," and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    if "".join(cur).strip():
        parts.append("".join(cur).strip())
    return parts


TYPE_STOP = ("NOT NULL", "NULL", "DEFAULT", "CONSTRAINT", "PRIMARY KEY", "UNIQUE",
             "REFERENCES", "CHECK", "GENERATED", "COLLATE")


def parse_column(part: str) -> dict | None:
    m = re.match(r'^"([^"]+)"\s+(.*)$', part) or re.match(r"^([A-Za-z_][A-Za-z0-9_]*)\s+(.*)$", part)
    if not m:
        return None
    name, rest = m.group(1), m.group(2).strip()
    upper = rest.upper()
    cut = len(rest)
    for kw in TYPE_STOP:
        idx = upper.find(kw)
        if idx >= 0:
            cut = min(cut, idx)
    sql_type = " ".join(rest[:cut].split())
    tail = rest[cut:]
    default = ""
    dm = re.search(r"DEFAULT\s+(.+?)(?=\s+(?:NOT NULL|NULL|CONSTRAINT|PRIMARY KEY|UNIQUE|REFERENCES|CHECK)\b|$)", tail, re.S)
    if dm:
        default = " ".join(dm.group(1).split())
    nullable = "NOT NULL" not in tail.upper()
    ref = re.search(r"REFERENCES\s+(?:public\.)?\"?([A-Za-z_][A-Za-z0-9_]*)\"?\s*\(([^)]+)\)", tail, re.I)
    return {
        "name": name, "sql_type": sql_type or "unknown", "nullable": nullable,
        "default": default, "pk": "PRIMARY KEY" in tail.upper(), "unique": "UNIQUE" in tail.upper(),
        "references": (ref.group(1), ref.group(2).strip().strip('"')) if ref else None,
    }


def merge_column(entry: dict, col: dict) -> None:
    """Merge a column definition; a later ALTER must not erase NOT NULL/PK info."""
    old = entry["columns"].get(col["name"])
    if not old:
        entry["columns"][col["name"]] = col
        return
    merged = dict(old)
    for key in ("sql_type", "default", "references"):
        if col.get(key):
            merged[key] = col[key]
    merged["nullable"] = old.get("nullable", True) and col.get("nullable", True)
    merged["pk"] = old.get("pk", False) or col.get("pk", False)
    merged["unique"] = old.get("unique", False) or col.get("unique", False)
    entry["columns"][col["name"]] = merged


def version_key(name: str) -> tuple:
    m = re.match(r"([\d.]+)", name)
    nums = tuple(int(x) for x in m.group(1).split(".") if x.isdigit()) if m else ()
    return (nums, name)


def parse_migrations() -> dict[str, dict]:
    info: dict[str, dict] = {}
    if not MIGRATIONS_DIR.is_dir():
        return info
    for mig in sorted((p for p in MIGRATIONS_DIR.iterdir() if p.is_dir()), key=lambda p: version_key(p.name)):
        up = mig / "up.sql"
        if not up.is_file():
            continue
        sql = strip_sql_comments(read(up))
        for m in re.finditer(r"CREATE TABLE\s+(?:IF NOT EXISTS\s+)?(?:public\.)?\"?([A-Za-z_][A-Za-z0-9_]*)\"?\s*\((.*?)\)\s*;", sql, re.S | re.I | re.M):
            table, body = m.group(1), m.group(2)
            entry = info.setdefault(table, {"migration": mig.name, "columns": {}, "indexes": [], "constraints": [], "comment": ""})
            entry["migration"] = mig.name
            for part in split_top_level(body):
                up_part = part.upper()
                if up_part.startswith(("CONSTRAINT ", "PRIMARY KEY", "UNIQUE", "CHECK", "FOREIGN KEY")):
                    entry["constraints"].append(" ".join(part.split()))
                    pk = re.search(r"PRIMARY KEY\s*\(([^)]+)\)", part, re.I)
                    if pk:
                        for col in pk.group(1).split(","):
                            c = entry["columns"].setdefault(col.strip().strip('"'), {"name": col.strip().strip('"')})
                            c["pk"] = True
                    fk = re.search(r"FOREIGN KEY\s*\(([^)]+)\)\s*REFERENCES\s+(?:public\.)?\"?([A-Za-z_][A-Za-z0-9_]*)\"?\s*\(([^)]+)\)", part, re.I)
                    if fk:
                        col = fk.group(1).split(",")[0].strip().strip('"')
                        c = entry["columns"].setdefault(col, {"name": col})
                        c["references"] = (fk.group(2), fk.group(3).split(",")[0].strip().strip('"'))
                    continue
                col = parse_column(part)
                if col:
                    merge_column(entry, col)
        for m in re.finditer(r"ALTER TABLE\s+(?:IF EXISTS\s+)?(?:ONLY\s+)?(?:public\.)?\"?([A-Za-z_][A-Za-z0-9_]*)\"?\s+(.*?);", sql, re.S | re.I | re.M):
            table, body = m.group(1), m.group(2)
            entry = info.setdefault(table, {"migration": mig.name, "columns": {}, "indexes": [], "constraints": [], "comment": ""})
            entry["migration"] = mig.name
            am = re.match(r"ADD COLUMN\s+(?:IF NOT EXISTS\s+)?(.*)$", body, re.S | re.I)
            if am:
                col = parse_column(am.group(1).strip())
                if col:
                    merge_column(entry, col)
            fm = re.search(r"ADD CONSTRAINT\s+\S+\s+FOREIGN KEY\s*\(([^)]+)\)\s*REFERENCES\s+(?:public\.)?\"?([A-Za-z_][A-Za-z0-9_]*)\"?\s*\(([^)]+)\)", body, re.I)
            if fm:
                col = fm.group(1).split(",")[0].strip().strip('"')
                c = entry["columns"].setdefault(col, {"name": col})
                c["references"] = (fm.group(2), fm.group(3).split(",")[0].strip().strip('"'))
            entry["constraints"].append(" ".join(f"ALTER TABLE {table} {body}".split()))
        for m in re.finditer(r"CREATE\s+(?:UNIQUE\s+)?INDEX\s+(?:IF NOT EXISTS\s+)?\"?([A-Za-z_][A-Za-z0-9_]*)\"?\s+ON\s+(?:public\.)?\"?([A-Za-z_][A-Za-z0-9_]*)\"?\s+(?:USING\s+\w+\s+)?\(([^)]*)\)", sql, re.I | re.M):
            entry = info.setdefault(m.group(2), {"migration": mig.name, "columns": {}, "indexes": [], "constraints": [], "comment": ""})
            entry["indexes"].append(f"{m.group(1)}({', '.join(c.strip() for c in m.group(3).split(','))})")
        for m in re.finditer(r"COMMENT ON TABLE\s+(?:public\.)?\"?([A-Za-z_][A-Za-z0-9_]*)\"?\s+IS\s+'([^']*)'", sql, re.I | re.M):
            entry = info.setdefault(m.group(1), {"migration": mig.name, "columns": {}, "indexes": [], "constraints": [], "comment": ""})
            entry["comment"] = m.group(2)
    return info


def build_inventory() -> dict:
    gates = module_features()
    tables: dict[str, dict] = {}
    edges: list[dict] = []
    groups = 0
    for path in rust_files():
        for t in parse_tables(path):
            t["feature"] = feature_of(path, gates)
            t["module"] = t["source"].split("botschema/src/")[-1].split("/")[0].removesuffix(".rs")
            tables.setdefault(t["name"], t)
        edges.extend(parse_joinables(path))
        groups += len(re.findall(r"allow_tables_to_appear_in_same_query!", strip_rust_comments(read(path))))
    migs = parse_migrations()
    for name, t in tables.items():
        mig = migs.get(name, {})
        t["migration"] = mig.get("migration", "")
        t["comment"] = mig.get("comment", "")
        t["indexes"] = sorted(set(mig.get("indexes", [])))
        t["constraints"] = sorted(set(mig.get("constraints", [])))
        mcols = mig.get("columns", {})
        for col in t["columns"]:
            mc = mcols.get(col["name"])
            if mc:
                col.update({
                    "sql_type": mc.get("sql_type") or sql_type_for(col["rust_type"]),
                    "nullable": mc.get("nullable", True), "default": mc.get("default", ""),
                    "pk": mc.get("pk", False), "unique": mc.get("unique", False),
                    "references": mc.get("references"),
                })
            else:
                col.update({
                    "sql_type": sql_type_for(col["rust_type"]),
                    "nullable": "Nullable<" in col["rust_type"], "default": "", "pk": False,
                    "unique": False, "references": None,
                })
            col["in_migration"] = col["name"] in mcols
        for col in t["pk"]:
            for c in t["columns"]:
                if c["name"] == col:
                    c["pk"] = True
        for c in t["columns"]:
            if c["pk"]:
                c["nullable"] = False
        t["missing_in_migrations"] = sorted(c["name"] for c in t["columns"] if not c["in_migration"])
        t["extra_in_migrations"] = sorted(set(mcols) - {c["name"] for c in t["columns"]})
    return {"tables": tables, "edges": edges, "groups": groups, "migrations": migs}


def report(inv: dict) -> None:
    tables, migs = inv["tables"], inv["migrations"]
    by_domain: dict[str, int] = {}
    by_gate: dict[str, int] = {}
    for t in tables.values():
        by_domain[t["module"]] = by_domain.get(t["module"], 0) + 1
        g = t["feature"] or "always available"
        by_gate[g] = by_gate.get(g, 0) + 1
    print(f"tables in botschema: {len(tables)}")
    print(f"columns: {sum(len(t['columns']) for t in tables.values())}")
    print(f"joinable! edges: {len(inv['edges'])}")
    print(f"allow_tables_to_appear_in_same_query! groups: {inv['groups']}")
    print("\nper domain:")
    for d in sorted(by_domain):
        print(f"  {d}: {by_domain[d]}")
    print("\nper feature gate:")
    for g in sorted(by_gate):
        print(f"  {g}: {by_gate[g]}")
    print("\nper table (columns, pk, nullable):")
    for t in sorted(tables.values(), key=lambda x: x["name"]):
        pks = [c["name"] for c in t["columns"] if c["pk"]] or t["pk"] or ["?"]
        nullable = sum(1 for c in t["columns"] if c["nullable"])
        print(f"  {t['name']}: cols={len(t['columns'])} pk={','.join(pks)} "
              f"nullable={nullable} mig={t['migration'] or 'none'}")
    drift_mig = sorted(set(migs) - set(tables))
    drift_schema = sorted(t["name"] for t in tables.values() if not t["migration"])
    print(f"\nin migrations but not in botschema: {len(drift_mig)}")
    for name in drift_mig:
        print(f"  {name} ({migs[name]['migration']})")
    print(f"\nin botschema with no migration: {len(drift_schema)}")
    for name in drift_schema:
        print(f"  {name}")
    col_drift = [(t["name"], c) for t in tables.values() for c in t["missing_in_migrations"]]
    print(f"\ncolumns missing from migrations: {len(col_drift)}")
    for name, col in col_drift:
        print(f"  {name}.{col}")


