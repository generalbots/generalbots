#!/usr/bin/env python3
"""Generate the BotBook app registry and version matrix from source manifests.

Sources: botserver/src/apps/registry/{entries.rs,entries_extra.rs,ownership.rs},
root Cargo.toml and botserver/3rdparty.toml. The SUMMARY.md blocks are regenerated
too, so a new app or component appears in the published book without prose edits.

Usage:
    python3 scripts/gen_source_catalogs.py           # write pages
    python3 scripts/gen_source_catalogs.py --check   # exit 1 on drift
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BOOK = ROOT / "botbook" / "src"
REGISTRY = ROOT / "botserver" / "src" / "apps" / "registry"
CARGO = ROOT / "Cargo.toml"
THIRDPARTY = ROOT / "botserver" / "3rdparty.toml"
SUMMARY = BOOK / "SUMMARY.md"

APP_PAGE = BOOK / "07-user-interface" / "apps" / "generated" / "registry.md"
VERSION_PAGE = BOOK / "12-ecosystem-reference" / "generated" / "versions.md"
NAV_PAGE = BOOK / "NAV.md"
APP_LINK = "   - [Generated app registry](./07-user-interface/apps/generated/registry.md)"
VER_LINK = "   - [Generated version matrix](./12-ecosystem-reference/generated/versions.md)"

APP_SPEC = re.compile(r"AppSpec\s*\{(.*?)\}", re.S)
FIELD = re.compile(r'^\s*(\w+):\s*"([^"]*)",', re.M)
OWNER = re.compile(r'\("([^"]+)",\s*"([^"]+)",\s*AppStatus::(\w+)\)')
VERSION = re.compile(r"\b(\d+\.\d+(?:\.\d+)?)\b")


def app_rows() -> list[tuple[str, ...]]:
    rows: list[tuple[str, ...]] = []
    for name in ("entries.rs", "entries_extra.rs"):
        text = (REGISTRY / name).read_text(encoding="utf-8")
        for match in APP_SPEC.finditer(text):
            fields = dict(FIELD.findall(match.group(1)))
            before = text[max(0, match.start() - 160):match.start()]
            visibility = "Always" if "always" in before.split("AppSpec")[-1] else "Preview"
            rows.append((fields.get("id", ""), fields.get("title", ""),
                         fields.get("category", ""), visibility,
                         fields.get("url", ""), fields.get("description", "")))
    ownership = dict(
        (app, (owner, status)) for app, owner, status in
        OWNER.findall((REGISTRY / "ownership.rs").read_text(encoding="utf-8"))
    )
    out = []
    for app, title, category, visibility, url, description in sorted(rows):
        owner, status = ownership.get(app, ("unowned", "Preview"))
        has_page = (BOOK / "07-user-interface" / "apps" / f"{app}.md").is_file()
        has_screen = (BOOK / "assets" / "suite" / f"{app}-screen.svg").is_file()
        out.append((app, title, category, status, owner, visibility,
                    "yes" if has_page else "no", "yes" if has_screen else "no",
                    url, description))
    return out


def version_rows() -> list[tuple[str, str, str]]:
    cargo = tomllib.loads(CARGO.read_text(encoding="utf-8"))
    product = cargo["workspace"]["package"]["version"]
    manifest = tomllib.loads(THIRDPARTY.read_text(encoding="utf-8"))
    rows = [("product (Cargo.toml)", "General Bots", product)]
    for key, component in sorted(manifest.get("components", {}).items()):
        name = component.get("name", key)
        filename = component.get("filename", "") or component.get("url", "")
        match = VERSION.search(filename)
        if match and "_cached" not in key and key not in {"models", "legacy_cache"}:
            rows.append((key, name, match.group(1)))
    return rows


def app_markdown() -> str:
    lines = [
        "<!-- GENERATED by scripts/gen_source_catalogs.py — do not edit by hand. -->",
        "",
        "# App Registry (generated) 🟡 BETA",
        "",
        f"{len(app_rows())} apps from `all_apps()` (entries + entries_extra). Status and "
        "owner come from `registry/ownership.rs`; launcher visibility comes from the "
        "registry constructor. Page/screen columns show what BotBook currently ships.",
        "",
        "| ID | Title | Category | Status | Owner | Launcher | Page | Screen |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for app, title, category, status, owner, visibility, page, screen, _url, _desc in app_rows():
        lines.append(f"| `{app}` | {title} | {category} | {status} | {owner} | "
                     f"{visibility} | {page} | {screen} |")
    lines += ["", "## Routes", "", "| ID | Suite route |", "|---|---|"]
    for app, _title, _category, _status, _owner, _vis, _p, _s, url, _desc in app_rows():
        lines.append(f"| `{app}` | `{url}` |")
    return "\n".join(lines) + "\n"


def version_markdown() -> str:
    lines = [
        "<!-- GENERATED by scripts/gen_source_catalogs.py — do not edit by hand. -->",
        "",
        "# Version Matrix (generated) 🟡 BETA",
        "",
        "Pins from `Cargo.toml` and `botserver/3rdparty.toml`. Legacy cache copies "
        "are intentionally excluded: they are not the versions the installer fetches.",
        "",
        "| Component | Name | Version |",
        "|---|---|---|",
    ]
    for key, name, version in version_rows():
        lines.append(f"| `{key}` | {name} | {version} |")
    return "\n".join(lines) + "\n"


def nav_markdown() -> str:
    """Turn SUMMARY.md's heading + list layout into one nav list for literate-nav.

    literate-nav reads a single list (the first one after `<!--nav-->`), while
    SUMMARY.md is several lists separated by headings. NAV.md is generated so
    both the guard (SUMMARY.md) and the renderer (NAV.md) stay in sync.
    """
    lines = ["<!--nav-->", ""]
    pending = ""
    for raw in SUMMARY.read_text(encoding="utf-8").splitlines():
        heading = re.match(r"^#+\s+(.*)", raw)
        if heading:
            pending = heading.group(1).strip()
            continue
        if raw.strip() in {"", "---"} or raw.lstrip().startswith("<!--"):
            continue
        item = re.match(r"^(\s*)-\s+(\[.*?\]\([^)]+\))", raw)
        flat = re.match(r"^(\[.*?\]\([^)]+\))", raw)
        if item or flat:
            had_pending = bool(pending)
            if pending:
                lines.append(f"- {pending}")
                pending = ""
            if item:
                indent = "    " * max(1, len(item.group(1)) // 3)
                lines.append(indent + "- " + item.group(2))
            else:
                lines.append(("    " if had_pending else "") + "- " + flat.group(1))
    return "\n".join(lines) + "\n"


def update_summary(text: str) -> str:
    """Keep exactly one nav line per generated page, at its current position."""
    for needle, line in ((APP_LINK.split("]")[0], APP_LINK), (VER_LINK.split("]")[0], VER_LINK)):
        lines = text.splitlines(keepends=True)
        seen = False
        out: list[str] = []
        for existing in lines:
            if needle in existing:
                if not seen:
                    out.append(line + "\n")
                    seen = True
                continue
            out.append(existing)
        if not seen:
            raise SystemExit(f"SUMMARY.md is missing the nav slot for {needle}")
        text = "".join(out)
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    pages = {APP_PAGE: app_markdown(), VERSION_PAGE: version_markdown(),
             NAV_PAGE: nav_markdown(),
             SUMMARY: update_summary(SUMMARY.read_text(encoding="utf-8"))}
    stale = [str(path.relative_to(ROOT)) for path, body in pages.items()
             if not path.is_file() or path.read_text(encoding="utf-8") != body]
    if args.check:
        for path in stale:
            print(f"gen_source_catalogs: stale {path}")
        print(f"gen_source_catalogs: {len(pages) - len(stale)}/{len(pages)} pages up to date")
        return 1 if stale else 0
    for path, body in pages.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8")
    print(f"gen_source_catalogs: wrote {len(pages)} files "
          f"({len(app_rows())} apps, {len(version_rows())} versions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
