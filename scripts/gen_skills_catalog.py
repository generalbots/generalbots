#!/usr/bin/env python3
"""Skills catalog generator (#2080): `botbook/src/13-ai-os/skills-catalog.md`.

Sources:

* ``botskills/<category>/<skill>/SKILL.md`` — YAML front matter (`name`,
  `description`, `source`, `allowed-tools`). A skill is instructions plus
  optional support files, not compiled code.
* ``botskills/README.md`` — skills catalogued by name and link only, because
  their upstream is a paid subscription and no files ship here.

Usage
-----
    python3 scripts/gen_skills_catalog.py --report   # inventory
    python3 scripts/gen_skills_catalog.py --check    # exit 1 when stale
"""

from __future__ import annotations

import argparse
import re
import sys

from catalog_common import SKILLS, SKILL_BEGIN, SKILL_END, SKILLS_PAGE, anchor, cell, read

SKILL_CATEGORY_ORDER = [
    "automation", "business", "content", "data", "design", "documentation",
    "engineering", "frontend", "integration", "media", "office", "operations",
    "quality", "research", "testing",
]


def parse_skills() -> list[dict]:
    skills: list[dict] = []
    for path in sorted(SKILLS.glob("*/*/SKILL.md")):
        text = read(path)
        front = re.match(r"---\n(.*?)\n---", text, re.S)
        meta = front.group(1) if front else ""
        name = re.search(r"^name:\s*(.+)$", meta, re.M)
        source = re.search(r"^source:\s*(.+)$", meta, re.M)
        tools = re.search(r"^allowed-tools:\s*\n((?:\s+-\s*.+\n?)+)", meta, re.M)
        description = re.search(r"^description:\s*[|>]?\s*\n?((?:.+\n)+?)(?=^\w|^---|\Z)", meta, re.M)
        summary = ""
        if description:
            summary = " ".join(line.strip() for line in description.group(1).splitlines()).strip()
        skills.append({
            "category": path.parent.parent.name,
            "name": name.group(1).strip() if name else path.parent.name,
            "purpose": summary.split(". ")[0].rstrip(".") + "." if summary else "",
            "source": source.group(1).strip() if source else "not declared",
            "tools": re.findall(r"-\s*(.+)", tools.group(1)) if tools else [],
        })
    return skills


def parse_linked_only() -> list[dict]:
    """Skills named in botskills/README.md but not shipped in the repository."""
    text = read(SKILLS / "README.md")
    return [
        {
            "category": match.group(1),
            "name": match.group(2),
            "url": match.group(3),
            "purpose": match.group(4).strip(),
        }
        for match in re.finditer(
            r"^\|\s*([a-z_]+)\s*\|\s*\[([^\]]+)\]\(([^)]+)\)\s*\|\s*([^|]+)\|", text, re.M
        )
    ]


def render_skills(skills: list[dict], linked: list[dict]) -> str:
    categories: dict[str, list[dict]] = {}
    for skill in skills:
        categories.setdefault(skill["category"], []).append(skill)
    ordered = [c for c in SKILL_CATEGORY_ORDER if c in categories]
    ordered += sorted(c for c in categories if c not in SKILL_CATEGORY_ORDER)
    lines = [
        "# Skills Catalog",
        "",
        SKILL_BEGIN,
        "Generated by `scripts/gen_catalogs.py` from `botskills/**/SKILL.md`; do not",
        "edit by hand.",
        SKILL_END,
        "",
        "A skill is instructions plus optional support files — Markdown and scripts,",
        "not compiled code. Installing one copies the package into the bot's Drive",
        "bucket and records the install; the prompt advertises each enabled skill as",
        "one `name: description` line, so bodies never enter the system prompt.",
        "",
        "## Install",
        "",
        "- `POST /api/sources/skills` — parse the front matter, hash the document and",
        "  store it with `enabled = TRUE`.",
        "- `GET /api/marketplace/skills` — browse the public catalog; installing from",
        "  the storefront adds the permission consent card first.",
        "- `scripts/install-skills.sh --token \"$TOKEN\"` — install every skill in this",
        "  repository (`--dry-run` to preview).",
        "",
        f"## Totals — {len(skills)} skills in this repository, {len(linked)} linked only",
        "",
        "| Category | Skills |",
        "|---|---:|",
    ]
    lines += [f"| [{category}](#{anchor(category)}) | {len(categories[category])} |"
              for category in ordered]
    for category in ordered:
        lines += [
            "",
            f"## {category}",
            "",
            f"Files live at `botskills/{category}/<skill>/SKILL.md`.",
            "",
            "| Skill | Purpose | Source | Permissions |",
            "|---|---|---|---|",
        ]
        for skill in sorted(categories[category], key=lambda s: s["name"].lower()):
            tools = ", ".join(f"`{tool}`" for tool in skill["tools"]) or "none declared"
            lines.append(
                f"| `{cell(skill['name'])}` | {cell(skill['purpose'])} "
                f"| {cell(skill['source'])} | {cell(tools)} |"
            )
    lines += [
        "",
        "## Linked only — not included in this repository",
        "",
        "These skills are catalogued by name and link because their upstream is a",
        "paid subscription; no files ship here.",
        "",
        "| Category | Skill | Note |",
        "|---|---|---|",
    ]
    for entry in sorted(linked, key=lambda e: (e["category"], e["name"])):
        lines.append(
            f"| {entry['category']} | [{cell(entry['name'])}]({entry['url']}) "
            f"| {cell(entry['purpose'])} |"
        )
    lines.append("")
    return "\n".join(lines)


def build_skills() -> tuple[str, list[dict], list[dict]]:
    skills = parse_skills()
    linked = parse_linked_only()
    return render_skills(skills, linked), skills, linked


def summary_block() -> str:
    return SKILL_BEGIN + "\n   - [Skills Catalog](./13-ai-os/skills-catalog.md)\n" + SKILL_END + "\n"


def report() -> int:
    _, skills, linked = build_skills()
    categories: dict[str, int] = {}
    for skill in skills:
        categories[skill["category"]] = categories.get(skill["category"], 0) + 1
    print(f"skills: {len(skills)} in-repo, {len(linked)} linked only")
    print("  " + ", ".join(f"{k}={v}" for k, v in sorted(categories.items())))
    declared = sum(1 for skill in skills if skill["tools"])
    print(f"skills declaring allowed-tools: {declared}/{len(skills)}")
    for entry in linked:
        print(f"  linked only: {entry['category']}/{entry['name']}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", action="store_true", help="print the inventory")
    parser.add_argument("--check", action="store_true", help="fail when the page is stale")
    args = parser.parse_args()
    if args.report:
        return report()
    body, _, _ = build_skills()
    stale = not SKILLS_PAGE.is_file() or read(SKILLS_PAGE) != body
    if args.check:
        if stale:
            print(f"stale: {SKILLS_PAGE}")
            print("gen_skills_catalog: run python3 scripts/gen_catalogs.py")
            return 1
        print("gen_skills_catalog: page up to date")
        return 0
    print("gen_skills_catalog: use scripts/gen_catalogs.py to write the page")
    return 0


if __name__ == "__main__":
    sys.exit(main())
