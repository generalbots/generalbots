#!/usr/bin/env python3
"""Status-aware #2546 guards: 410 tombstones and 501 handlers (fail-closed).

A route generated by `gone_handler!` always answers 410 Gone: it never reads a
request, so advertising it to the LLM can only produce a failed plan. A handler
that returns `StatusCode::NOT_IMPLEMENTED` may stay in the source inventory only
when `api_catalog::NOT_IMPLEMENTED_ENDPOINTS` names an owner — that list is what
filters it from `api.find`.

Imported by `scripts/check_route_contract.py`; not a standalone CLI.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Iterable

REPO_ROOT = Path(__file__).resolve().parents[1]
RETIRED_HANDLER = re.compile(r"\bgone_handler!\s*\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*,")
FN_NAME = re.compile(r"^(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+([A-Za-z_][A-Za-z0-9_]*)")
FN_START = re.compile(r"(?m)^[ \t]*(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+")


def _source_key(source: str | Path) -> str:
    """Crate directory, so same-named handlers in different crates stay distinct."""
    try:
        relative = Path(source).relative_to(REPO_ROOT)
    except ValueError:
        relative = Path(source)
    parts = relative.parts
    if "src" in parts:
        return "/".join(parts[: parts.index("src")])
    return "/".join(parts[:2])


def parse_retired_handlers(paths: Iterable[Path]) -> set[tuple[str, str]]:
    """(crate, name) pairs generated by the fails-closed `gone_handler!` macro."""
    names: set[tuple[str, str]] = set()
    for path in paths:
        try:
            text = path.read_text(errors="ignore")
        except OSError:
            continue
        crate = _source_key(path)
        names.update((crate, name) for name in RETIRED_HANDLER.findall(text))
    return names


def parse_not_implemented_handlers(paths: Iterable[Path]) -> set[tuple[str, str]]:
    """(crate, name) pairs of functions returning StatusCode::NOT_IMPLEMENTED."""
    names: set[tuple[str, str]] = set()
    for path in paths:
        try:
            text = path.read_text(errors="ignore")
        except OSError:
            continue
        if "StatusCode::NOT_IMPLEMENTED" not in text:
            continue
        crate = _source_key(path)
        starts = [match.start() for match in FN_START.finditer(text)]
        for index, start in enumerate(starts):
            end = starts[index + 1] if index + 1 < len(starts) else len(text)
            if "StatusCode::NOT_IMPLEMENTED" not in text[start:end]:
                continue
            found = FN_NAME.match(text[start:].lstrip())
            if found:
                names.add((crate, found.group(1)))
    return names


def route_matches(catalog_path: str, router_path: str, canonical: Callable[[str], str]) -> bool:
    """Exact match, or nested-router suffix match (mount prefix added at runtime)."""
    catalog, router = canonical(catalog_path), canonical(router_path)
    return catalog == router or (router.count("/") >= 2 and catalog.endswith(router))


def check_status_contract(
    endpoints: Iterable,
    registrations: Iterable,
    not_implemented: Iterable[tuple[str, str, str]],
    retired_handlers: set[tuple[str, str]],
    handler_names: set[tuple[str, str]],
    canonical: Callable[[str], str],
) -> list[str]:
    """Fail on advertised tombstones, unowned 501s and stale gap entries."""
    problems: list[str] = []
    documented = {(e.method.upper(), canonical(e.path)): e for e in endpoints}
    declared = {(m.upper(), canonical(p)) for m, p, _ in not_implemented}
    by_method: dict[str, list] = {}
    for registration in registrations:
        by_method.setdefault(registration.method.upper(), []).append(registration)

    def mounted(method: str, path: str) -> list:
        return [
            entry
            for entry in by_method.get(method.upper(), ())
            if route_matches(path, entry.path, canonical)
        ]

    for method, path, _owner in not_implemented:
        if not mounted(method, path):
            problems.append(f"not-implemented gap {method} {path} has no mounted route")
    for (method, path), endpoint in documented.items():
        found = mounted(method, path)
        handlers = {
            (_source_key(entry.source), entry.handler.split("::")[-1]) for entry in found
        }
        if found and handlers.issubset(retired_handlers):
            problems.append(
                f"retired 410 route advertised: {endpoint.method} {endpoint.path} "
                f"({endpoint.source})"
            )
            continue
        if (method, path) in declared:
            continue
        for _crate, handler in sorted(handlers & handler_names):
            problems.append(
                f"NOT_IMPLEMENTED handler {handler} advertised without owner: "
                f"{endpoint.method} {endpoint.path} ({endpoint.source})"
            )
    return problems


def self_test() -> int:
    """Prove each status rule fires and the declared-owner escape hatches work."""
    @dataclass(frozen=True)
    class Endpoint:
        method: str
        path: str
        source: str = "inv.rs"

    @dataclass(frozen=True)
    class Registration:
        method: str
        path: str
        handler: str
        source: str = "route.rs"

    def canonical(path: str) -> str:
        return re.sub(r":([A-Za-z_][A-Za-z0-9_]*)", r"{\1}", path)

    gone = Endpoint("POST", "/api/sales/email/webhook")
    gone_route = [Registration("POST", "/api/sales/email/webhook", "gone_webhook")]
    unimplemented = Endpoint("POST", "/api/auth/2fa/verify")
    nested = [Registration("POST", "/2fa/verify", "verify_2fa")]
    clean = [Endpoint("GET", "/api/ok")]

    def check(
        endpoints: list,
        registrations: list,
        declared: list | None = None,
        retired: set[tuple[str, str]] | None = None,
        handlers: set[tuple[str, str]] | None = None,
    ) -> list[str]:
        return check_status_contract(
            endpoints, registrations, declared or [], retired or set(), handlers or set(), canonical
        )

    gone_key = ("route.rs", "gone_webhook")
    assert any("retired 410 route advertised" in p for p in check([gone], gone_route, retired={gone_key})), "tombstone not detected"
    assert any("without owner" in p for p in check([gone], gone_route, handlers={gone_key})), "unowned 501 not detected"
    assert not check([gone], gone_route, declared=[("POST", "/api/sales/email/webhook", "owner.rs")]), "owner list ignored"
    assert any("no mounted route" in p for p in check([], [], declared=[("GET", "/api/nope", "owner.rs")])), "stale gap not detected"
    assert any("without owner" in p for p in check([unimplemented], nested, handlers={("route.rs", "verify_2fa")})), "nested 501 not detected"
    assert not check(clean, [Registration("GET", "/api/ok", "ok")]), "clean contract rejected"
    print("status guard self-test: 6 checks passed")
    return 0
