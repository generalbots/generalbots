#!/usr/bin/env python3
"""Render the generated BASIC keyword/function reference (issue #2079).

Input is the inventory produced by `scripts/basic_parse.py`, which reads the
real registrations. Output goes to `botbook/src/04-basic-scripting/generated/`.

Usage:
    python3 scripts/gen_basic_reference.py --report   # inventory to stdout
    python3 scripts/gen_basic_reference.py            # write the pages
    python3 scripts/gen_basic_reference.py --check    # fail on drift

Standard library only, no network, deterministic output.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from basic_parse import REPO, build_inventory
from basic_report import report

OUT_DIR = REPO / "botbook" / "src" / "04-basic-scripting" / "generated"
GEN_NOTE = "<!-- generated by scripts/gen_basic_reference.py — do not edit by hand -->"
MAX_LINES = 380
STATUS_NOTE = {
    "registered": "`register_custom_syntax` / `register_fn` exists",
    "alias-of-rewrite": "rewritten by `convert_multiword_keywords.rs`",
    "directive": "consumed by the compiler preprocessor, not a runtime syntax",
    "documented-only": "named by `get_all_keywords()` with no registration",
}


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


def cell(text: str) -> str:
    return text.replace("|", "\\|") if text else "—"


def docs_cell(entry: dict) -> str:
    return f"[page]({entry['docs']})" if entry["docs"] else "—"


def source_cell(entry: dict) -> str:
    sources = entry.get("sources") or [entry["source"]]
    first = sources[0]
    more = f" (+{len(sources) - 1})" if len(sources) > 1 else ""
    return f"`{first}`{more}"


def keyword_rows(keywords: list[dict]) -> list[str]:
    rows = ["| Keyword | Signature | Status | Source | Docs | Purpose |", "|---|---|---|---|---|---|"]
    for k in keywords:
        rows.append(f"| `{k['name']}` | `{cell(k['signature'])}` | {k['status']} | "
                    f"{source_cell(k)} | {docs_cell(k)} | {cell(k['purpose'])} |")
    return rows


def function_rows(functions: list[dict]) -> list[str]:
    rows = ["| Function | Aliases | Status | Source | Docs | Purpose |", "|---|---|---|---|---|---|"]
    for f in functions:
        aliases = ", ".join(f"`{a}`" for a in f["aliases"]) or "—"
        rows.append(f"| `{f['name']}` | {aliases} | {f['status']} | {source_cell(f)} | "
                    f"{docs_cell(f)} | {cell(f['purpose'])} |")
    return rows


def chunk(rows: list[str], header: list[str]) -> list[list[str]]:
    chunks, current = [], []
    for row in rows:
        if current and len(current) + len(header) + 12 > MAX_LINES:
            chunks.append(current)
            current = []
        current.append(row)
    if current:
        chunks.append(current)
    return chunks


def category_pages(inv: dict) -> dict[str, str]:
    by_category: dict[str, list[dict]] = {}
    for k in inv["keywords"]:
        by_category.setdefault(k["category"], []).append(k)
    functions_by_category: dict[str, list[dict]] = {}
    for f in inv["functions"]:
        functions_by_category.setdefault(f["category"], []).append(f)
    pages: dict[str, str] = {}
    for category in sorted(set(by_category) | set(functions_by_category)):
        kw_rows = keyword_rows(by_category.get(category, []))
        fn_rows = function_rows(functions_by_category.get(category, []))
        head = [GEN_NOTE, "", f"# BASIC keywords: {category}", "",
                "Part of the [generated BASIC reference](./index.md). "
                "Status and purpose come from the registration in the source file, "
                "never from a hand-written list.", ""]
        body = ["## Keywords", ""] + kw_rows[0:2] + kw_rows[2:] + [""]
        body += ["## Functions", ""] + fn_rows[0:2] + fn_rows[2:] + [""]
        parts = chunk(body, head)
        for idx, part in enumerate(parts, start=1):
            name = f"{category}.md" if idx == 1 else f"{category}-{idx}.md"
            title = f"# BASIC keywords: {category}" + ("" if idx == 1 else f" (part {idx})")
            page_head = [GEN_NOTE, "", title, "",
                         "Part of the [generated BASIC reference](./index.md). "
                         "Status and purpose come from the registration in the source file, "
                         "never from a hand-written list.", ""]
            pages[name] = "\n".join(page_head + part).rstrip() + "\n"
    return pages


def index_page(inv: dict, pages: dict[str, str]) -> str:
    keywords, functions = inv["keywords"], inv["functions"]
    syntax = [k for k in keywords if k["status"] != "directive"]
    counts: dict[str, list[int]] = {}
    for k in keywords:
        counts.setdefault(k["category"], [0, 0])[0] += 1
    for f in functions:
        counts.setdefault(f["category"], [0, 0])[1] += 1
    lines = [GEN_NOTE, "", "# Generated BASIC Reference", "",
             "Built from the registrations in `botserver/crates/botbasic_*/src/**` and",
             "`botserver/src/basic/keywords/**`, plus the compiler's directive table and",
             "rewrite aliases. Regenerate with:", "",
             "```bash",
             "python3 scripts/gen_basic_reference.py            # write the pages",
             "python3 scripts/gen_basic_reference.py --check     # fail on drift",
             "python3 scripts/gen_basic_reference.py --report    # inventory only",
             "```", "",
             f"Composite keyword registrations: **{len(syntax)}** "
             f"({len({k['name'] for k in syntax})} distinct forms) · "
             f"functions: **{len(functions)}** · rewrite aliases: **{len(inv['aliases'])}** · "
             f"compiler directives: **{len(inv['directives'])}**", "",
             "## Status legend", "", "| Status | Meaning |", "|---|---|"]
    for status in ("registered", "alias-of-rewrite", "directive", "documented-only"):
        lines.append(f"| `{status}` | {STATUS_NOTE[status]} |")
    lines += ["", "## Categories", "", "| Category | Keywords | Functions | Page |", "|---|---|---|---|"]
    for category in sorted(counts):
        names = sorted(p for p in pages if p == f"{category}.md" or p.startswith(f"{category}-"))
        links = " · ".join(f"[{n[:-3]}](./{n})" for n in names)
        lines.append(f"| `{category}` | {counts[category][0]} | {counts[category][1]} | {links} |")
    documented = sum(1 for k in keywords if k["purpose"])
    documented_fns = sum(1 for f in functions if f["purpose"])
    lines += ["", "## Engine-provided keywords", "",
              "These are Rhai builtins (`convert_while_wend_syntax.rs`), so no registration",
              "exists and none is needed: " + ", ".join(f"`{b}`" for b in inv["builtins"]) + ".",
              "", "## Purpose coverage", "",
              f"The purpose column is filled from a `//!` module comment or the `///` doc",
              f"comment of the owning function. Today it covers **{documented}/{len(keywords)}**",
              f"keywords and **{documented_fns}/{len(functions)}** functions; `—` means the",
              "source carries no doc comment, not that the keyword is undocumented here.",
              "", "## Advertised but not registered", "",
              "`get_all_keywords()` (`botserver/src/basic/keywords/mod.rs`) lists names that",
              "have no `register_custom_syntax`, `register_fn`, directive or rewrite behind",
              "them. A name in that list is not proof of implementation; this table is the",
              "drift report, not a feature list.", ""]
    if inv["documented_only"]:
        lines += ["| Name | `.bas` templates using it |", "|---|---|"]
        for name in inv["documented_only"]:
            lines.append(f"| `{name}` | {inv['template_usage'].get(name, 0)} |")
    else:
        lines.append("None: every advertised name has a registration.")
    add_tool = inv["template_usage"].get("ADD TOOL", 0)
    if add_tool:
        lines += ["", f"`ADD TOOL` is template-only: {add_tool} `.bas` files under `bottemplates/`",
                  "use it, no registration exists, and `USE TOOL` is the implemented form.",
                  "Either implement it as an alias of `USE TOOL` or migrate those templates;",
                  "until then the reference never marks it implemented."]
    lines += ["", "## See also", "",
              "- [Keyword overview](./../keywords.md)",
              "- [Grammar summary](./grammar-summary.md)",
              "- [Hand-written keyword pages](./../keywords.md)"]
    return "\n".join(lines).rstrip() + "\n"


def grammar_page(inv: dict) -> str:
    keywords = inv["keywords"]
    blocks = sorted((k for k in keywords if k["block"]), key=lambda k: k["signature"])
    first_tokens: dict[str, list[dict]] = {}
    for k in keywords:
        first_tokens.setdefault(k["name"].split()[0], []).append(k)
    collisions = {t: sorted(v, key=lambda x: x["signature"])
                  for t, v in first_tokens.items() if len(v) > 1}
    lines = [GEN_NOTE, "", "# BASIC Grammar Summary (derived)", "",
             "Everything on this page is derived from the registered syntax arrays and the",
             "compiler's own tables. Where the parser has no registration to point at, the",
             "fact is absent rather than guessed. The normative statement grammar lives in",
             "`botserver/crates/botbasic_compiler/src/syntax_transforms/`.", "",
             "## Block constructs", "",
             "A `$block$` placeholder is a statement sequence terminated by the trailing",
             "literal tokens of the same registration.", "",
             "| Form | Source |", "|---|---|"]
    for k in blocks:
        lines.append(f"| `{k['signature']}` | `{k['source']}:{k['line']}` |")
    lines += ["", "## Statements grouped by first token", "",
              "Rhai keys custom syntax by the first token, so this grouping is also the",
              "runtime dispatch unit. `$expr$`, `$ident$`, `$string$`, `$int$`, `$bool$`",
              "and `$block$` are the only argument forms the registrations use.", "",
              "| First token | Registered forms |", "|---|---|"]
    for token in sorted(first_tokens):
        forms = sorted({k["signature"] for k in first_tokens[token]})
        lines.append(f"| `{token}` | " + "<br>".join(f"`{f}`" for f in forms) + " |")
    lines += ["", "## First-token collisions", "",
              "Two registrations sharing a first token overwrite each other in the engine's",
              "syntax map: only the last one registered is reachable at runtime. The",
              "compiler rewrites the affected forms to function calls; the forms below are",
              "the ones that must be checked against `convert_multiword_keywords.rs`.",
              "", "| First token | Forms |", "|---|---|"]
    for token in sorted(collisions):
        lines.append(f"| `{token}` | " + "<br>".join(f"`{k['signature']}`" for k in collisions[token]) + " |")
    lines += ["", "## Compiler directives", "",
              "Directives are consumed by `preprocess_basic.rs`, not by the Rhai engine, and",
              "are validated for conflicts in `directive_conflicts.rs`.", "",
              "| Directive | Source |", "|---|---|"]
    for d in inv["directives"]:
        lines.append(f"| `{d['name']}` | `{d['source']}` |")
    lines += ["", "## Rewrite aliases", "",
              "`convert_multiword_keywords.rs` rewrites these forms into plain function calls",
              "before evaluation, which is why a form can be usable without a runtime syntax.",
              "", "| Written form | Rewritten to | Arguments |", "|---|---|---|"]
    for a in inv["aliases"]:
        args = ", ".join(a["args"]) or "—"
        lines.append(f"| `{a['name']}` | `{a['function']}(…)` | {args} |")
    return "\n".join(lines).rstrip() + "\n"


def render(inv: dict) -> dict[Path, str]:
    pages = category_pages(inv)
    files = {OUT_DIR / name: body for name, body in pages.items()}
    files[OUT_DIR / "index.md"] = index_page(inv, pages)
    files[OUT_DIR / "grammar-summary.md"] = grammar_page(inv)
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--report", action="store_true", help="print the inventory")
    ap.add_argument("--check", action="store_true", help="fail when pages are stale")
    args = ap.parse_args()
    inv = build_inventory()
    if args.report:
        report(inv)
        return 0
    files = render(inv)
    if args.check:
        stale = [p for p, body in files.items() if not p.is_file() or read(p) != body]
        summary = REPO / "botbook" / "src" / "SUMMARY.md"
        summary_text = read(summary) if summary.is_file() else ""
        book_src = REPO / "botbook" / "src"
        unregistered = [p for p in files
                        if book_src in p.parents and f"(./{p.relative_to(book_src)})" not in summary_text]
        for p in stale:
            print(f"stale: {p.relative_to(REPO)}")
        for p in unregistered:
            print(f"not in SUMMARY.md: {p.relative_to(book_src)}")
        for claim in inv["doc_claims"]:
            print(f"documented but not registered: {claim['name']} "
                  f"(botbook/src/04-basic-scripting/{claim['page']})")
        return 1 if stale or unregistered or inv["doc_claims"] else 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, body in sorted(files.items()):
        path.write_text(body, encoding="utf-8")
    over = [p for p, b in files.items() if b.count("\n") > 450]
    syntax = sum(1 for k in inv["keywords"] if k["status"] != "directive")
    print(f"wrote {len(files)} files: {syntax} keyword registrations, "
          f"{len(inv['directives'])} directives, {len(inv['functions'])} functions, "
          f"{len(inv['aliases'])} aliases, {len(inv['documented_only'])} advertised-but-unregistered")
    for p in over:
        print(f"WARNING: {p.relative_to(REPO)} exceeds 450 lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
