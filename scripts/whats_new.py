#!/usr/bin/env python3
"""What's New generator for the product release line.

The desktop opens a "What's New" window when the running version differs from
the last version the user has seen.  The window reads ``whatsnew.md``, which is
compiled into ``botserver`` and served at ``/api/whats-new``.  This script is
what writes that file when a release is tagged.

Commands
--------
``current``
    Print the newest product tag (``vX.Y.Z``), or the workspace version when no
    tag is reachable.
``generate --version vX.Y.Z``
    Build (or replace) the section for that version from issues closed since the
    previous tag.  ``--write`` updates the file; without it the section is
    printed.
``render --version vX.Y.Z``
    Print the body of an existing section (used for the release page).
``check [--version vX.Y.Z]``
    Exit non-zero when the version has no section.  Useful as a CI guard.

The script only uses the Python standard library.  Issue data comes from ``gh``
when it is installed and authenticated, from the REST API with ``GITHUB_TOKEN``
otherwise, or from ``--from-json`` for offline tests.

Environment
-----------
``WHATS_NEW_LABEL``
    When set, only issues carrying that label enter the changelog.  Use it to
    pin the entries that are user-facing instead of shipping every closed issue.
``WHATS_NEW_LIMIT``
    Maximum number of issues fetched (default 200).
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import urllib.error
import urllib.request
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WHATS_NEW = ROOT / "whatsnew.md"
REPO = os.environ.get("GITHUB_REPOSITORY", "generalbots/generalbots")

HEADER = """# What's New in General Bots

<!-- Generated by scripts/whats_new.py when a release is tagged. Newest release
     first. Do not edit by hand: `generate --version` replaces that section. -->

"""

SECTION_RE = re.compile(r"(?m)^##\s+v?(\d+\.\d+\.\d+)\b")

# A closed issue is only a shipped change when it is not one of these.
EXCLUDED_LABELS = {
    "duplicate",
    "invalid",
    "wontfix",
    "question",
    "backlog",
    "pending test",
    "epic",
    "internal",
}

GROUPS = [
    ("security", "Security", {"security"}),
    ("features", "Features", {"enhancement", "feature", "feature-request"}),
    ("fixes", "Fixes", {"bug", "fix"}),
    ("internal", "Internal", {"ci", "cleanup", "dependencies", "refactor", "chore"}),
]

CONVENTIONAL = re.compile(
    r"^(feat|fix|chore|docs|ci|refactor|perf|test|security|build)(\([^)]*\))?:\s*",
    re.IGNORECASE,
)


def warn(message: str) -> None:
    print(f"whats_new: {message}", file=sys.stderr)


def git(*args: str) -> str:
    try:
        return subprocess.run(
            ["git", *args],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        ).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return ""


def product_tags() -> list[tuple[str, str]]:
    """Return ``[(tag, date)]`` newest first."""
    raw = git("tag", "-l", "v*", "--sort=-v:refname")
    tags: list[tuple[str, str]] = []
    for tag in raw.splitlines():
        if not re.fullmatch(r"v\d+\.\d+\.\d+", tag):
            continue
        date = git("log", "-1", "--format=%cs", tag) or datetime.now().date().isoformat()
        tags.append((tag, date))
    return tags


def current_version() -> str:
    tags = product_tags()
    if tags:
        return tags[0][0].lstrip("v")
    cargo = (ROOT / "Cargo.toml").read_text(encoding="utf-8")
    match = re.search(r'(?m)^version\s*=\s*"(\d+\.\d+\.\d+)"', cargo)
    if not match:
        raise SystemExit("cannot determine the current version")
    return match.group(1)


def previous_tag(version: str) -> tuple[str, str] | None:
    for tag, date in product_tags():
        if tag.lstrip("v") != version:
            return tag, date
    return None


def normalize_version(raw: str) -> str:
    value = raw.strip().lstrip("v")
    if not re.fullmatch(r"\d+\.\d+\.\d+", value):
        raise SystemExit(f"not a vMAJOR.MINOR.PATCH version: {raw}")
    return value


def split_file(text: str) -> tuple[str, list[str]]:
    """Return ``(header, [section_block, ...])``, newest first preserved."""
    matches = list(SECTION_RE.finditer(text))
    if not matches:
        header = text
        return header, []
    header = text[: matches[0].start()]
    blocks: list[str] = []
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        blocks.append(text[match.start() : end])
    return header, blocks


def join_file(header: str, blocks: list[str]) -> str:
    body = "\n".join(block.strip() + "\n" for block in blocks)
    return (header.rstrip() + "\n\n" + body).strip() + "\n"


def replace_section(text: str, version: str, block: str) -> str:
    header, blocks = split_file(text)
    kept = [
        existing
        for existing in blocks
        if not re.match(rf"^##\s+v?{re.escape(version)}\b", existing)
    ]
    return join_file(header, [block] + kept)


def section_body(text: str, version: str) -> str | None:
    _, blocks = split_file(text)
    for block in blocks:
        if re.match(rf"^##\s+v?{re.escape(version)}\b", block):
            return block.strip()
    return None


def clean_title(title: str) -> str:
    return CONVENTIONAL.sub("", title).strip() or title.strip()


def label_names(issue: dict) -> set[str]:
    names: set[str] = set()
    for label in issue.get("labels") or []:
        name = label.get("name") if isinstance(label, dict) else str(label)
        if name:
            names.add(name.lower())
    return names


def group_for(labels: set[str]) -> str:
    for key, _, names in GROUPS:
        if labels & names:
            return key
    return "other"


def fetch_issues(since: str) -> list[dict]:
    limit = os.environ.get("WHATS_NEW_LIMIT", "200")
    if _has_gh():
        command = [
            "gh",
            "issue",
            "list",
            "--repo",
            REPO,
            "--state",
            "closed",
            "--limit",
            limit,
            "--search",
            f"closed:>={since}",
            "--json",
            "number,title,labels,closedAt,url",
        ]
        try:
            result = subprocess.run(command, check=True, capture_output=True, text=True)
            return json.loads(result.stdout or "[]")
        except (subprocess.CalledProcessError, json.JSONDecodeError) as error:
            warn(f"gh issue list failed ({error}); trying the REST API")

    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    url = (
        f"https://api.github.com/repos/{REPO}/issues"
        f"?state=closed&since={since}T00:00:00Z&per_page=100"
    )
    request = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json"})
    if token:
        request.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            payload = json.loads(response.read().decode("utf-8"))
    except (urllib.error.URLError, json.JSONDecodeError) as error:
        warn(f"GitHub API unavailable ({error}); generating an empty section")
        return []
    return [issue for issue in payload if "pull_request" not in issue]


def _has_gh() -> bool:
    try:
        subprocess.run(["gh", "--version"], check=True, capture_output=True)
        return True
    except (subprocess.CalledProcessError, FileNotFoundError):
        return False


ISSUE_REF = re.compile(r"#(\d{2,6})")


def commit_issue_refs(previous: tuple[str, str] | None) -> set[int]:
    """Issues referenced by the commits that actually landed since the tag.

    Closed issues are noisy — a busy day closes dozens, most of them never
    shipped. The commit subjects are the shipped set, and every merge in this
    repository names the issues it closes, so the intersection is the honest
    changelog.
    """
    if not previous:
        return set()
    raw = git("log", "--format=%s", f"{previous[0]}..HEAD")
    return {int(number) for number in ISSUE_REF.findall(raw)}


def commit_subjects(previous: tuple[str, str] | None) -> list[str]:
    """Commit subjects as a last resort when no issue survives the filters."""
    if not previous:
        return []
    raw = git("log", "--format=%s", f"{previous[0]}..HEAD")
    return [
        line.strip()
        for line in raw.splitlines()
        if line.strip() and not line.startswith("chore(release)")
    ]


def build_section(
    version: str,
    date: str,
    issues: list[dict],
    commits: list[str] | None = None,
) -> str:
    required = os.environ.get("WHATS_NEW_LABEL", "").strip().lower()
    grouped: dict[str, list[dict]] = {key: [] for key, _, _ in GROUPS}
    grouped["other"] = []
    seen: set[int] = set()
    for issue in issues:
        number = issue.get("number")
        if not isinstance(number, int) or number in seen:
            continue
        labels = label_names(issue)
        if labels & EXCLUDED_LABELS:
            continue
        if required and required not in labels:
            continue
        title = clean_title(str(issue.get("title") or "").strip())
        if not title or title.lower().startswith("chore(release)"):
            continue
        seen.add(number)
        grouped[group_for(labels)].append({"number": number, "title": title})

    lines = [f"## v{version} — {date}", ""]
    for key, title, _ in GROUPS:
        items = grouped.get(key) or []
        if not items:
            continue
        lines.append(f"### {title}")
        for item in sorted(items, key=lambda value: value["number"]):
            lines.append(f"- {item['title']} (#{item['number']})")
        lines.append("")
    other = grouped.get("other") or []
    if other:
        lines.append("### Other")
        for item in sorted(other, key=lambda value: value["number"]):
            lines.append(f"- {item['title']} (#{item['number']})")
        lines.append("")

    has_items = any(grouped[key] for key, _, _ in GROUPS) or other
    if not has_items and commits:
        lines.append("### Changes")
        for subject in commits:
            lines.append(f"- {subject}")
        lines.append("")

    return "\n".join(lines).strip() + "\n"


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.exists() else HEADER


def command_current(_: argparse.Namespace) -> int:
    print(current_version())
    return 0


def command_generate(args: argparse.Namespace) -> int:
    version = normalize_version(args.version)
    previous = previous_tag(version)
    since = args.since or (
        previous[1]
        if previous
        else (datetime.now() - timedelta(days=30)).date().isoformat()
    )
    date = args.date or datetime.now(timezone.utc).date().isoformat()

    if args.from_json:
        issues = json.loads(Path(args.from_json).read_text(encoding="utf-8"))
        commits: list[str] = []
    else:
        issues = fetch_issues(since)
        shipped = commit_issue_refs(previous)
        if shipped:
            issues = [issue for issue in issues if issue.get("number") in shipped]
        # No issue survives the filters (still open, or labelled backlog): fall
        # back to the commit subjects so the section is never blank.
        commits = commit_subjects(previous) if not issues else []

    block = build_section(version, date, issues, commits)
    path = Path(args.file) if args.file else WHATS_NEW
    text = read_text(path)
    updated = replace_section(text, version, block)
    if args.write:
        path.write_text(updated, encoding="utf-8")
        print(f"wrote {path} ({len(issues)} issues since {since})")
    else:
        print(block)
    return 0


def command_render(args: argparse.Namespace) -> int:
    version = normalize_version(args.version)
    path = Path(args.file) if args.file else WHATS_NEW
    block = section_body(read_text(path), version)
    if not block:
        warn(f"no section for v{version} in {path}")
        return 1
    print(block)
    return 0


def command_check(args: argparse.Namespace) -> int:
    version = normalize_version(args.version) if args.version else current_version()
    path = Path(args.file) if args.file else WHATS_NEW
    if section_body(read_text(path), version):
        print(f"whatsnew.md has a section for v{version}")
        return 0
    warn(f"whatsnew.md has no section for v{version}")
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--file", help="override the markdown path (tests)")
    sub = parser.add_subparsers(dest="command", required=True)

    current = sub.add_parser("current", help="print the newest product version")
    current.set_defaults(func=command_current)

    generate = sub.add_parser("generate", help="build a version section")
    generate.add_argument("--version", required=True)
    generate.add_argument("--since", help="ISO date; defaults to the previous tag")
    generate.add_argument("--date", help="section date (default today)")
    generate.add_argument("--from-json", help="read issues from a JSON file")
    generate.add_argument("--write", action="store_true")
    generate.set_defaults(func=command_generate)

    render = sub.add_parser("render", help="print an existing section")
    render.add_argument("--version", required=True)
    render.set_defaults(func=command_render)

    check = sub.add_parser("check", help="fail when a version has no section")
    check.add_argument("--version")
    check.set_defaults(func=command_check)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
