#!/usr/bin/env bash
# Generate a throwaway UEFI Secure Boot signing key pair for development and
# CI (#2478). The private key NEVER belongs in the repository: it is created
# into a caller-chosen directory outside the tree (a private mktemp dir by
# default) and is only meant to be used for the current build.
#
# Outputs:
#   db.key   PEM private key (0600) — pass to mkosi --secure-boot-key=
#   db.crt   PEM X.509 certificate — pass to mkosi --secure-boot-certificate=
#   db.cer   DER form of the certificate — `sudo mokutil --import db.cer`
#   env.sh   shell fragment exporting GB_SB_KEY / GB_SB_CERT / GB_SB_MOK_CER
#
# Production deployments must supply their own offline-held key pair with
# --key/--cert on desktop/os/build-image.sh instead of this throwaway pair.
set -euo pipefail

die() { printf 'generate-secure-boot-keys: %s\n' "$*" >&2; exit 1; }

usage() {
    cat <<'USAGE'
Usage: desktop/os/generate-secure-boot-keys.sh [options]

  --output-dir DIR     where to write the key material (default: mktemp -d)
  --common-name NAME   X.509 CN (default: "General Bots OS Secure Boot (dev)")
  --days N             certificate validity in days (default: 730)
  -h, --help           show this help

The output directory is created mode 0700 and must be OUTSIDE the repository.
USAGE
}

output_dir=""
common_name="General Bots OS Secure Boot (dev)"
days=730

while [ "$#" -gt 0 ]; do
    case "$1" in
        --output-dir)    output_dir="${2:-}"; [ "$#" -ge 2 ] || die "--output-dir needs a value"; shift ;;
        --output-dir=*)  output_dir="${1#*=}" ;;
        --common-name)   common_name="${2:-}"; [ "$#" -ge 2 ] || die "--common-name needs a value"; shift ;;
        --common-name=*) common_name="${1#*=}" ;;
        --days)          days="${2:-}"; [ "$#" -ge 2 ] || die "--days needs a value"; shift ;;
        --days=*)        days="${1#*=}" ;;
        -h|--help)       usage; exit 0 ;;
        *)               die "unknown option: $1" ;;
    esac
    shift
done

case "$days" in
    ''|*[!0-9]*) die "--days must be a positive integer" ;;
    0)           die "--days must be a positive integer" ;;
esac

command -v openssl >/dev/null 2>&1 \
    || die "openssl is required to generate Secure Boot keys"

# Locate the repository root so we can refuse to write secrets inside it.
script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(git -C "$script_dir" rev-parse --show-toplevel 2>/dev/null || true)"

if [ -z "$output_dir" ]; then
    output_dir="$(mktemp -d "${TMPDIR:-/tmp}/gb-secure-boot.XXXXXX")"
fi
mkdir -p -m 0700 -- "$output_dir"
chmod 0700 -- "$output_dir"

abs_dir="$(cd -- "$output_dir" && pwd -P)"
if [ -n "$repo_root" ]; then
    case "$abs_dir/" in
        "$(cd -- "$repo_root" && pwd -P)/"*) \
            die "refusing to write private keys inside the repository ($abs_dir)" ;;
    esac
fi

key="$abs_dir/db.key"
crt="$abs_dir/db.crt"
cer="$abs_dir/db.cer"
env_file="$abs_dir/env.sh"

# Self-signed code-signing certificate. -nodes is safe here: this key is a
# throwaway build artifact, not a long-lived production signing identity.
openssl req -x509 -newkey rsa:2048 -nodes -sha256 \
    -keyout "$key" -out "$crt" -days "$days" \
    -subj "/CN=${common_name}/" \
    -addext "keyUsage=digitalSignature" \
    -addext "extendedKeyUsage=codeSigning" >/dev/null 2>&1
openssl x509 -in "$crt" -outform DER -out "$cer"

chmod 0600 -- "$key"
chmod 0644 -- "$crt" "$cer"

cat >"$env_file" <<EOF
# Generated by desktop/os/generate-secure-boot-keys.sh — do NOT commit.
export GB_SB_KEY='$key'
export GB_SB_CERT='$crt'
export GB_SB_MOK_CER='$cer'
EOF
chmod 0600 -- "$env_file"

printf 'Secure Boot signing material written to: %s\n' "$abs_dir"
printf '  private key (NEVER commit): %s\n' "$key"
printf '  certificate (PEM):          %s\n' "$crt"
printf '  MOK certificate (DER):      %s\n' "$cer"
printf '\nBuild a signed image:\n'
printf "  GB_SB_KEY='%s' GB_SB_CERT='%s' desktop/os/build-image.sh --mode release\n" "$key" "$crt"
printf '\nEnrol the MOK certificate on the target machine (shim/MokManager flow):\n'
printf '  sudo mokutil --import %s\n' "$cer"
